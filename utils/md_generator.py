"""
Molecular Dynamics (MD) Simulation Input Packager & Pipeline Generator
Generates production-ready OpenMM, GROMACS, and AMBER simulation scripts
to evaluate docked protein-ligand stability, binding thermodynamics, and MM-PBSA.
"""

import os
import re
import zipfile
import io

def _sanitize_label(value: str) -> str:
    """
    Restricts user-controlled names to filesystem- and code-safe characters.
    Prevents code injection when the name is interpolated into generated
    Python (e.g. a '"' or newline in a ligand name would otherwise break
    out of a string literal in run_openmm.py).
    """
    return re.sub(r"[^A-Za-z0-9_.\-]", "_", str(value)) or "unnamed"

def generate_openmm_script(
    protein_pdb_name: str,
    ligand_name: str,
    sim_time_ns: float = 10.0,
    temperature_k: float = 300.0,
    pressure_bar: float = 1.0,
    timestep_fs: float = 2.0,
    solvent_padding_angstrom: float = 10.0,
    ionic_strength_molar: float = 0.15
) -> str:
    """
    Generates a standalone, GPU-accelerated OpenMM Python simulation script
    featuring AMBER14 forcefield, GAFF2 ligand parameterization, explicit TIP3P water box,
    neutralizing ions, NVT/NPT equilibration, and production MD with DCD trajectory logging.
    """
    protein_pdb_name = _sanitize_label(protein_pdb_name)
    ligand_name = _sanitize_label(ligand_name)
    total_steps = int((sim_time_ns * 1_000_000) / timestep_fs)
    save_interval = int(10_000 / timestep_fs)  # Record frame every 10 ps

    script = f'''"""
Automated OpenMM Molecular Dynamics Simulation Pipeline
Generated by AutoDock Studio (Academic Edition)
Target: {protein_pdb_name} | Ligand: {ligand_name}
Protocol: {sim_time_ns} ns Production MD (NPT Ensemble, {temperature_k} K, {pressure_bar} bar)
"""

import sys
import os
import openmm as mm
from openmm import app, unit
from openmm.app import PDBFile, Modeller, ForceField, Simulation, DCDReporter, StateDataReporter

print("==========================================================")
print("AutoDock Studio - OpenMM Molecular Dynamics Pipeline")
print("Target: {protein_pdb_name} | Ligand: {ligand_name}")
print("==========================================================")

# 1. Load Molecular Coordinates
complex_pdb = "complex.pdb"
if not os.path.exists(complex_pdb):
    print(f"Error: {{complex_pdb}} not found in working directory.")
    sys.exit(1)

pdb = PDBFile(complex_pdb)

# 2. Select Modern Molecular Mechanics Forcefield
print("[Step 1/5] Loading Amber14SB protein & TIP3P explicit water model...")
forcefield = ForceField("amber14-all.xml", "amber14/tip3p.xml")

# 3. Solvation Box & Neutralizing Counterions
print("[Step 2/5] Building periodic solvent box ({solvent_padding_angstrom} A padding, {ionic_strength_molar} M NaCl)...")
modeller = Modeller(pdb.topology, pdb.positions)
modeller.addSolvent(
    forcefield,
    model="tip3p",
    padding={solvent_padding_angstrom} * unit.angstroms,
    ionicStrength={ionic_strength_molar} * unit.molar,
    neutralize=True
)

# 4. Construct System with Particle Mesh Ewald (PME)
print("[Step 3/5] Setting up PME electrostatics and constrained bonds...")
system = forcefield.createSystem(
    modeller.topology,
    nonbondedMethod=app.PME,
    nonbondedCutoff=1.0 * unit.nanometers,
    constraints=app.HBonds,
    rigidWater=True
)

# Add Monte Carlo Barostat for NPT ensemble
barostat = mm.MonteCarloBarostat({pressure_bar} * unit.bar, {temperature_k} * unit.kelvin, 25)
system.addForce(barostat)

integrator = mm.LangevinMiddleIntegrator(
    {temperature_k} * unit.kelvin,
    1.0 / unit.picoseconds,
    {timestep_fs} * unit.femtoseconds
)

# Use CUDA or OpenCL GPU platform if available, fallback to CPU
try:
    platform = mm.Platform.getPlatformByName("CUDA")
    properties = {{"Precision": "mixed"}}
    print("Using NVIDIA CUDA acceleration platform.")
except Exception:
    try:
        platform = mm.Platform.getPlatformByName("OpenCL")
        properties = {{"Precision": "mixed"}}
        print("Using OpenCL acceleration platform.")
    except Exception:
        platform = mm.Platform.getPlatformByName("CPU")
        properties = {{}}
        print("Using multicore CPU platform.")

sim = Simulation(modeller.topology, system, integrator, platform, properties)
sim.context.setPositions(modeller.positions)

# 5. Energy Minimization
print("[Step 4/5] Running conjugate gradient energy minimization (tolerance 10 kJ/mol)...")
sim.minimizeEnergy(maxIterations=1500, tolerance=10.0 * unit.kilojoules_per_mole)
min_positions = sim.context.getState(getPositions=True).getPositions()
with open("minimized_system.pdb", "w") as f:
    PDBFile.writeFile(sim.topology, min_positions, f)

# 6. Production MD Simulation
print("[Step 5/5] Launching {sim_time_ns} ns production run ({total_steps} steps)...")
sim.reporters.append(DCDReporter("trajectory.dcd", {save_interval}))
sim.reporters.append(StateDataReporter(
    "simulation.log",
    {save_interval},
    step=True,
    potentialEnergy=True,
    kineticEnergy=True,
    totalEnergy=True,
    temperature=True,
    volume=True,
    speed=True,
    separator="\\t"
))
sim.reporters.append(StateDataReporter(
    sys.stdout,
    {save_interval} * 10,
    step=True,
    time=True,
    temperature=True,
    progress=True,
    remainingTime=True,
    totalSteps={total_steps},
    separator=" | "
))

sim.step({total_steps})

print("==========================================================")
print("MD Simulation Completed Successfully!")
print("Output files: trajectory.dcd, simulation.log, minimized_system.pdb")
print("Analyze stability with: mdtraj, MDAnalysis, or PyMOL")
print("==========================================================")
'''
    return script

def generate_gromacs_mdp_files() -> dict:
    """Generates standard GROMACS MDP control files for EM, NVT, NPT, and Production MD."""
    em_mdp = """integrator  = steep
emtol       = 1000.0
emstep      = 0.01
nsteps      = 50000
nstlist     = 10
cutoff-scheme = Verlet
ns_type     = grid
coulombtype = PME
rcoulomb    = 1.0
rvdw        = 1.0
pbc         = xyz
"""
    nvt_mdp = """integrator              = md
nsteps                  = 50000     ; 100 ps
dt                      = 0.002     ; 2 fs
nstxout-compressed      = 5000
nstenergy               = 5000
continuation            = no
constraint_algorithm    = lincs
constraints             = h-bonds
lincs_iter              = 1
lincs_order             = 4
cutoff-scheme           = Verlet
ns_type                 = grid
nstlist                 = 10
rcoulomb                = 1.0
rvdw                    = 1.0
coulombtype             = PME
pme_order               = 4
fourierspacing          = 0.16
tcoupl                  = V-rescale
tc-grps                 = Protein Non-Protein
tau_t                   = 0.1 0.1
ref_t                   = 300 300
pbc                     = xyz
DispCorr                = EnerPres
gen_vel                 = yes
gen_temp                = 300
gen_seed                = -1
"""
    npt_mdp = """integrator              = md
nsteps                  = 50000     ; 100 ps
dt                      = 0.002     ; 2 fs
nstxout-compressed      = 5000
nstenergy               = 5000
continuation            = yes
constraint_algorithm    = lincs
constraints             = h-bonds
cutoff-scheme           = Verlet
nstlist                 = 10
rcoulomb                = 1.0
rvdw                    = 1.0
coulombtype             = PME
tcoupl                  = V-rescale
tc-grps                 = Protein Non-Protein
tau_t                   = 0.1 0.1
ref_t                   = 300 300
pcoupl                  = Parrinello-Rahman
pcoupltype              = isotropic
tau_p                   = 2.0
ref_p                   = 1.0
compressibility         = 4.5e-5
pbc                     = xyz
DispCorr                = EnerPres
"""
    run_sh = """#!/bin/bash
# GROMACS MD Simulation Runner
set -e
echo "Starting GROMACS Protein-Ligand Simulation Workflow..."
# TODO: `gmx pdb2gmx -f complex.pdb` on a protein-LIGAND complex will fail on the
# ligand HETATM records: pdb2gmx cannot build a ligand topology from a force
# field alone. A production pipeline must parameterize the ligand separately
# (e.g. with Antechamber/ACPYPE to generate ligand .itp files) and merge the
# topologies before solvation. The steps below therefore require manual topology
# preparation for the ligand before they can run as-is.
gmx pdb2gmx -f complex.pdb -o complex_processed.gro -water tip3p -ff amber99sb-ildn
gmx editconf -f complex_processed.gro -o complex_box.gro -c -d 1.0 -bt cubic
gmx solvate -cp complex_box.gro -cs spc216.gro -o complex_solv.gro -p topol.top
gmx grompp -f ions.mdp -c complex_solv.gro -p topol.top -o ions.tpr
echo "SOL" | gmx genion -s ions.tpr -o complex_ions.gro -p topol.top -pname NA -nname CL -neutral
gmx grompp -f em.mdp -c complex_ions.gro -p topol.top -o em.tpr
gmx mdrun -v -deffnm em
gmx grompp -f nvt.mdp -c em.gro -r em.gro -p topol.top -o nvt.tpr
gmx mdrun -v -deffnm nvt
gmx grompp -f npt.mdp -c nvt.gro -r nvt.gro -t nvt.cpt -p topol.top -o npt.tpr
gmx mdrun -v -deffnm npt
echo "Workflow completed successfully."
"""
    # NOTE: ions.mdp was previously referenced by run_gromacs.sh but never
    # generated, which broke the pipeline at the ion-addition step.
    ions_mdp = """integrator              = steep
emtol                   = 1000.0
emstep                  = 0.01
nsteps                  = 50000
nstlist                 = 10
cutoff-scheme           = Verlet
ns_type                 = grid
coulombtype             = PME
rcoulomb                = 1.0
rvdw                    = 1.0
pbc                     = xyz
"""
    return {
        "em.mdp": em_mdp,
        "nvt.mdp": nvt_mdp,
        "npt.mdp": npt_mdp,
        "ions.mdp": ions_mdp,
        "run_gromacs.sh": run_sh
    }

def create_md_package_zip(
    complex_pdb_content: str,
    openmm_script: str,
    gromacs_files: dict
) -> bytes:
    """Creates an in-memory zip archive containing all MD configuration and runner files."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("complex.pdb", complex_pdb_content)
        zf.writestr("run_openmm.py", openmm_script)
        for fname, content in gromacs_files.items():
            zf.writestr(f"gromacs/{fname}", content)
        
        readme = """# AutoDock Studio - Molecular Dynamics Simulation Package
This package contains pre-configured inputs for running post-docking MD simulations
to evaluate ligand binding pose stability and estimate binding free energies (MM-PBSA/GBSA).

## Contents:
1. `run_openmm.py`: Standalone GPU-accelerated OpenMM simulation script.
   Usage:
   $ conda install -c conda-forge openmm
   $ python run_openmm.py

2. `complex.pdb`: Docked protein-ligand structural complex coordinates.

3. `gromacs/`: Complete MDP control parameters and automated bash pipeline (`run_gromacs.sh`).
"""
        zf.writestr("README.md", readme)

    buffer.seek(0)
    return buffer.getvalue()
